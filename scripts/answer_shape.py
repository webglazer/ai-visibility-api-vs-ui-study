"""Answer shape: is the API answer shorter, with fewer brands and sources, than the website answer?
For each engine and prompt kind: median words, median/mean brands named, share of answers naming
10+ brands, median cited domains. Plus a per-prompt ratio: API brands / mean website brands for the
same prompt (website mean over its 5 runs). Uses data/entities.jsonl.gz for brands.
Writes results/answer_shape.csv and results/answer_shape.md."""
import csv, os, re, statistics as st, sys
from collections import defaultdict
sys.path.insert(0, os.path.dirname(__file__))
from common import DATA, STUDY, load_prompts, read_jsonl_gz
from analyze import domains_of

RES = os.path.join(STUDY, "results")
FILES = {"chatgpt": "bd_chatgpt", "gemini": "bd_gemini", "google": "bd_google",
         "chatgpt_api": "api_chatgpt", "gemini_api": "api_gemini"}
GROUPS = {"recommendation (global + Baltic buyer)": {"recommendation", "buyer", "local"},
          "informational / branded / identity": {"informational", "branded", "identity_en"},
          "all": None}


def words(r):
    t = r.get("answer_text_markdown") or r.get("answer_text") or ""
    t = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", t)
    t = re.sub(r"https?://\S+", "", t)
    return len(t.split())


def main():
    kind = {p["n"]: p["kind"] for p in load_prompts()}
    brands = {(e["engine"], e["n"], e["run"]): len(e["brands"]) for e in read_jsonl_gz(os.path.join(DATA, "entities.jsonl.gz"))}
    rows = defaultdict(list)  # (channel, n) -> [(words, brands, domains)]
    for ch, f in FILES.items():
        seen = set()
        for r in read_jsonl_gz(os.path.join(DATA, f + ".jsonl.gz")):
            if not r.get("usable"):
                continue
            k = (r["engine"], int(r["n"]), int(r.get("run") or 1))
            if k in seen or k not in brands:
                continue
            seen.add(k)
            rows[(ch, k[1])].append((words(r), brands[k], len(domains_of(r))))
    out = []
    for g, kinds in GROUPS.items():
        for ch in FILES:
            vals = [v for (c, n), vs in rows.items() if c == ch and (kinds is None or kind[n] in kinds) for v in vs]
            if not vals:
                continue
            w, b, d = zip(*vals)
            out.append({"group": g, "channel": ch, "answers": len(vals), "median_words": int(st.median(w)),
                        "median_brands": st.median(b), "mean_brands": round(st.mean(b), 1),
                        "pct_10plus_brands": round(100 * sum(x >= 10 for x in b) / len(b), 1),
                        "median_domains": st.median(d)})
    ratios = defaultdict(list)
    for eng, api in (("chatgpt", "chatgpt_api"), ("gemini", "gemini_api")):
        for (c, n), vs in rows.items():
            if c != api or (eng, n) not in rows or kind[n] not in GROUPS["recommendation (global + Baltic buyer)"]:
                continue
            site = st.mean(v[1] for v in rows[(eng, n)])
            if site >= 3:
                ratios[eng].append(vs[0][1] / site)
    os.makedirs(RES, exist_ok=True)
    with open(os.path.join(RES, "answer_shape.csv"), "w", newline="", encoding="utf-8") as fh:
        wr = csv.DictWriter(fh, fieldnames=list(out[0]))
        wr.writeheader()
        wr.writerows(out)
    lines = ["# Answer shape: API vs website (auto-generated by scripts/answer_shape.py)", ""]
    for g in GROUPS:
        lines += [f"## {g}", "", "| Channel | Answers | Median words | Median brands | Mean brands | 10+ brands | Median cited sites |",
                  "|---|---|---|---|---|---|---|"]
        lines += [f"| {r['channel']} | {r['answers']} | {r['median_words']} | {r['median_brands']} | {r['mean_brands']} | "
                  f"{r['pct_10plus_brands']}% | {r['median_domains']} |" for r in out if r["group"] == g]
        lines.append("")
    lines.append("## Per prompt: API brands as a share of website brands (recommendation prompts, website mean >= 3 brands)")
    for eng, rs in ratios.items():
        lines.append(f"- {eng}: median {st.median(rs):.2f}, API names fewer brands than the website average in "
                     f"{100 * sum(x < 1 for x in rs) / len(rs):.0f}% of prompts, half or fewer in "
                     f"{100 * sum(x <= 0.5 for x in rs) / len(rs):.0f}% (n={len(rs)})")
    open(os.path.join(RES, "answer_shape.md"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
